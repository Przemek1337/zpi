from __future__ import annotations

import platform
import shutil
import time
from typing import Dict, Optional, Tuple

import numpy as np
import optuna
import torch
from pydantic import BaseModel, ConfigDict

from fraud_detection.configuration.experiment_config import ExperimentConfig
from fraud_detection.data.dataset_source import ensure_prepared
from fraud_detection.data.transaction_set import TransactionSet
from fraud_detection.exceptions import DataValidationError, DeviceUnavailableError, TuningError
from fraud_detection.persistence.model_artifact_store import ModelArtifactStore
from fraud_detection.training.training_runner import TrainingRunner
from fraud_detection.tuning.study_factory import count_trials, fail_interrupted_trials, open_study
from fraud_detection.tuning.trial_objective import TrialObjective, quiet_training_logs, trial_config
from fraud_detection.tuning.tuning_config import TrialTrainingConfig, TuningConfig
from fraud_detection.utils.colored_logging import get_logger
from fraud_detection.utils.device_resolver import resolve_device

logger = get_logger(__name__)

SMOKE_DIRECTORY = ".preflight_smoke"


class PreflightReport(BaseModel):
    model_config = ConfigDict(frozen=True)

    train_rows: int
    validation_rows: int
    validation_fraud: int
    feature_count: int
    data_generated: bool
    device: str
    device_name: str
    existing_trials: Dict[str, int]
    best_value: Optional[float] = None
    interrupted_trials: int = 0
    smoke_seconds: float


class Preflight:
    """Verifies everything a long unattended tuning run depends on, failing within minutes instead of hours."""

    def __init__(self, base: ExperimentConfig, tuning: TuningConfig) -> None:
        self._base = base
        self._tuning = tuning

    def run(self) -> Tuple[PreflightReport, TransactionSet, TransactionSet, torch.device]:
        self._step(
            "Environment",
            f"Python {platform.python_version()}, torch {torch.__version__}, optuna {optuna.__version__}",
        )
        device, device_name = self._check_device()
        data_generated, train, validation = self._load_data()
        self._check_output_writable()
        study_counts, best_value, interrupted = self._check_study()
        smoke_seconds = self._smoke_test(train, validation, device)
        report = PreflightReport(
            train_rows=len(train),
            validation_rows=len(validation),
            validation_fraud=len(validation) - len(validation.with_label(self._base.data.legitimate_label)),
            feature_count=train.feature_count,
            data_generated=data_generated,
            device=str(device),
            device_name=device_name,
            existing_trials=study_counts,
            best_value=best_value,
            interrupted_trials=interrupted,
            smoke_seconds=smoke_seconds,
        )
        return report, train, validation, device

    def _check_device(self) -> Tuple[torch.device, str]:
        device = resolve_device(self._base.device)
        if device.type != "cuda":
            if self._tuning.preflight.require_gpu:
                raise DeviceUnavailableError(
                    f"Tuning resolved device '{device}' but preflight.require_gpu is set; "
                    "check CUDA drivers or set preflight.require_gpu: false to tune on CPU"
                )
            self._step("Device", f"{device} (no GPU - tuning will be slow)")
            return device, "CPU"
        properties = torch.cuda.get_device_properties(device)
        name = f"{properties.name}, {properties.total_memory / 1024**3:.1f} GB"
        self._step("Device", f"{device} ({name})")
        return device, name

    def _load_data(self) -> Tuple[bool, TransactionSet, TransactionSet]:
        data_generated = ensure_prepared(self._base.data)
        with quiet_training_logs():
            train, validation = TrainingRunner(self._base).load_datasets()
        legitimate_label = self._base.data.legitimate_label
        fraud = len(validation) - len(validation.with_label(legitimate_label))
        if fraud == 0:
            raise DataValidationError("Validation set has no fraud rows - the tuning objective (recall) is undefined")
        latent_high = self._tuning.search_space.latent_dim.high
        if latent_high >= train.feature_count:
            raise TuningError(
                f"search_space.latent_dim.high ({latent_high}) must be below the feature count ({train.feature_count})"
            )
        source = "generated by notebook" if data_generated else "existing"
        self._step(
            "Data",
            f"{source}; train {len(train)} legitimate, validation {len(validation)} ({fraud} fraud), "
            f"{train.feature_count} features",
        )
        return data_generated, train, validation

    def _check_output_writable(self) -> None:
        directory = self._tuning.output.directory
        probe = directory / ".write_probe"
        try:
            directory.mkdir(parents=True, exist_ok=True)
            probe.write_text("ok", encoding="utf-8")
            probe.unlink()
        except OSError as error:
            raise TuningError(f"Output directory {directory} is not writable: {error}") from error
        self._step("Output", f"{directory} writable")

    def _check_study(self) -> Tuple[Dict[str, int], Optional[float], int]:
        study = open_study(self._tuning)
        interrupted = fail_interrupted_trials(study)
        counts = count_trials(study)
        best_value = study.best_value if counts["complete"] else None
        if sum(counts.values()) == 0:
            self._step("Study", f"new study '{self._tuning.study.name}' in {self._tuning.study.storage}")
        else:
            best = "n/a" if best_value is None else f"{best_value:.1%}"
            self._step(
                "Study",
                f"resuming '{self._tuning.study.name}': {counts['complete']} complete, {counts['pruned']} pruned, "
                f"{counts['fail']} failed, best recall {best}",
            )
        if interrupted:
            logger.warning("Marked %d trial(s) interrupted by the previous run as failed", interrupted)
        return counts, best_value, interrupted

    def _smoke_test(self, train: TransactionSet, validation: TransactionSet, device: torch.device) -> float:
        """Runs a few tiny trials through the real objective, then saves and reloads a model."""
        settings = self._tuning.preflight
        smoke_tuning = self._tuning.model_copy(
            update={"trial": TrialTrainingConfig(epochs=settings.smoke_epochs, early_stopping_patience=1)}
        )
        smoke_train, smoke_validation = self._smoke_subsets(train, validation)
        objective = TrialObjective(self._base, smoke_tuning, smoke_train, smoke_validation, device)
        study = optuna.create_study(
            direction="maximize", sampler=optuna.samplers.RandomSampler(seed=self._tuning.study.sampler_seed)
        )
        started = time.perf_counter()
        for index in range(settings.smoke_trials):
            trial = study.ask()
            try:
                study.tell(trial, objective(trial))
            except Exception as error:
                study.tell(trial, state=optuna.trial.TrialState.FAIL)
                raise TuningError(
                    f"Smoke trial {index + 1}/{settings.smoke_trials} failed with {trial.params}: "
                    f"{type(error).__name__}: {error}"
                ) from error
        self._check_artifact_round_trip(smoke_tuning, study.best_trial, smoke_train, smoke_validation, device)
        seconds = time.perf_counter() - started
        self._step("Smoke test", f"{settings.smoke_trials} mini trials + model save/load passed in {seconds:.0f}s")
        return seconds

    def _smoke_subsets(
        self, train: TransactionSet, validation: TransactionSet
    ) -> Tuple[TransactionSet, TransactionSet]:
        settings = self._tuning.preflight
        legitimate = self._base.data.legitimate_label
        rows = np.flatnonzero(validation.labels != legitimate)
        rows = np.concatenate([
            np.flatnonzero(validation.labels == legitimate)[: settings.smoke_validation_legitimate_rows],
            rows,
        ])
        subset_train = TransactionSet(
            features=train.features[: settings.smoke_train_rows],
            labels=train.labels[: settings.smoke_train_rows],
            feature_names=train.feature_names,
        )
        subset_validation = TransactionSet(
            features=validation.features[rows], labels=validation.labels[rows], feature_names=validation.feature_names
        )
        return subset_train, subset_validation

    def _check_artifact_round_trip(
        self,
        smoke_tuning: TuningConfig,
        trial: optuna.trial.FrozenTrial,
        train: TransactionSet,
        validation: TransactionSet,
        device: torch.device,
    ) -> None:
        config = trial_config(self._base, smoke_tuning, optuna.trial.FixedTrial(trial.params))
        with quiet_training_logs():
            model, history = TrainingRunner(config).train(train, validation, device)
        store = ModelArtifactStore(self._tuning.output.directory / SMOKE_DIRECTORY)
        try:
            store.save_model(model, train.feature_names)
            store.save_history(history)
            store.save_config(config)
            store.load_model(device)
        finally:
            shutil.rmtree(store.directory, ignore_errors=True)

    @staticmethod
    def _step(name: str, detail: str) -> None:
        logger.info("[ OK ] %-11s %s", name, detail)
